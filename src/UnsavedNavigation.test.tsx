it('cancels logout without sending it and retains dirty protection after failed logout', async () => {
  window.history.replaceState({}, '', '/platform/settings/models')
  const logout = vi.fn().mockRejectedValue(new Error('退出失败'))
  const user = userEvent.setup()
  render(<RealApp user={TEST_ADMIN} onLogout={logout} />)
  await user.type(screen.getByLabelText('模型 ID'), 'draft')
  await user.click(screen.getByLabelText('用户菜单'))
  await user.click(screen.getByRole('button', { name: '退出登录' }))
  expect(logout).not.toHaveBeenCalled()
  await user.click(screen.getByRole('button', { name: '继续编辑' }))
  await user.click(screen.getByLabelText('用户菜单'))
  await user.click(screen.getByRole('button', { name: '退出登录' }))
  await user.click(screen.getByRole('button', { name: '放弃修改并离开' }))
  expect(await screen.findByRole('alert')).toHaveTextContent('退出失败')
  expect(logout).toHaveBeenCalledOnce()
  expect(screen.getByLabelText('模型 ID')).toHaveValue('draft')
  await user.click(screen.getByRole('button', { name: '项目管理' }))
  expect(screen.getByRole('dialog')).toBeInTheDocument()
})
