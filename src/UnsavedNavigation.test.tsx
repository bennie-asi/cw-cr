import { act, fireEvent, render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { expect, it, vi } from 'vitest'
import App from './test-app'
import RealApp from './App'
import { TEST_ADMIN } from './test-app'

it.each([
  ['models', '模型 ID'], ['notifications', '群名称'], ['system', 'GitLab API Token'],
])('protects unsaved %s input during sidebar navigation and unload', async (page, field) => {
  window.history.replaceState({}, '', `/platform/settings/${page}`)
  const user = userEvent.setup()
  render(<App />)
  await user.type(screen.getByLabelText(field), 'draft')
  const unload = new Event('beforeunload', { cancelable: true })
  fireEvent(window, unload)
  expect(unload.defaultPrevented).toBe(true)
  await user.click(screen.getByRole('button', { name: '项目管理' }))
  expect(screen.getByRole('dialog')).toHaveTextContent('未保存的修改')
  expect(window.location.pathname).toBe(`/platform/settings/${page}`)
  await user.click(screen.getByRole('button', { name: '继续编辑' }))
  expect(screen.getByLabelText(field)).toHaveValue('draft')
  await user.click(screen.getByRole('button', { name: '项目管理' }))
  await user.click(screen.getByRole('button', { name: '放弃修改并离开' }))
  expect(window.location.pathname).toBe('/platform/projects')
  const cleanUnload = new Event('beforeunload', { cancelable: true })
  fireEvent(window, cleanUnload)
  expect(cleanUnload.defaultPrevented).toBe(false)
})

