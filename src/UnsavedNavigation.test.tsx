it('protects policy prompts and discards them before returning to the project', async () => {
  window.history.replaceState({}, '', '/projects/demo-api/settings/policy')
  const user = userEvent.setup()
  render(<App />)
  await user.click(screen.getByRole('button', { name: '高级设置' }))
  const original = (screen.getByLabelText('中文总评提示词') as HTMLTextAreaElement).value
  if (!screen.queryByLabelText('中文总评提示词')) await user.click(screen.getByRole('button', { name: '高级设置' }))
  await user.type(screen.getByLabelText('中文总评提示词'), 'draft')
  await user.click(screen.getByRole('button', { name: '评审历史' }))
  await user.click(screen.getByRole('button', { name: '继续编辑' }))
  expect(screen.getByLabelText('中文总评提示词')).toHaveValue(original + 'draft')
  await user.click(screen.getByRole('button', { name: '评审历史' }))
  await user.click(screen.getByRole('button', { name: '放弃修改并离开' }))
  await user.click(screen.getByRole('button', { name: '项目策略' }))
  await user.click(screen.getByRole('button', { name: '高级设置' }))
  expect(screen.getByLabelText('中文总评提示词')).toHaveValue(original)
})

