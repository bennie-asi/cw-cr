it('cancels and then accepts a real browser back traversal without losing the forward entry', async () => {
  const user = userEvent.setup()
  render(<App />)
  await user.click(screen.getByRole('button', { name: '模型与引擎' }))
  await user.type(screen.getByLabelText('模型 ID'), 'draft')
  act(() => window.history.back())
  await screen.findByRole('dialog')
  expect(window.location.pathname).toBe('/platform/settings/models')
  await user.click(screen.getByRole('button', { name: '继续编辑' }))
  expect(screen.getByLabelText('模型 ID')).toHaveValue('draft')
  act(() => window.history.back())
  await user.click(await screen.findByRole('button', { name: '放弃修改并离开' }))
  await waitFor(() => expect(window.location.pathname).toBe('/'))
  expect(screen.queryByLabelText('模型 ID')).not.toBeInTheDocument()
  act(() => window.history.forward())
  await waitFor(() => expect(screen.getByLabelText('模型 ID')).toHaveValue(''))
})

