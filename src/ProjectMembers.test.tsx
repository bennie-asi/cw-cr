import { act, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { api } from './api'
import type { ManagedUser, ProjectMember } from './api'
import { ProjectMembers } from './ProjectMembers'

const member: ProjectMember = { id: 7, user_id: 8, username: 'alice', display_name: 'Alice', role: 'admin', is_active: true, platform_role: 'member' }
const props = { projectId: 'p1', projectName: 'Chaos', canManage: true, currentUserId: 1, onAccessChange: vi.fn() }
const createdAccount: ManagedUser = { id: 12, username: 'carol', display_name: 'Carol', platform_role: 'member', is_active: true, last_login: null }
const createdMember: ProjectMember = { ...member, id: 12, user_id: 12, username: 'carol', display_name: 'Carol', role: 'member' }
async function openMemberAction(user: ReturnType<typeof userEvent.setup>, action: 'edit' | 'remove') {
  await user.click(screen.getByRole('button', { name: 'Alice 的更多操作' }))
  await user.click(screen.getByRole('button', { name: action === 'edit' ? '修改 Alice 的角色' : '移除 Alice' }))
}
beforeEach(() => { vi.spyOn(api, 'listProjectMembers').mockResolvedValue([member]) })
afterEach(() => vi.restoreAllMocks())

it('loads and filters real members while distinguishing project role from platform role', async () => {
  const user = userEvent.setup()
  render(<ProjectMembers {...props} />)
  expect(await screen.findByText('Alice')).toBeInTheDocument()
  expect(api.listProjectMembers).toHaveBeenCalledWith('p1')
  expect(screen.getByText('平台成员')).toBeInTheDocument()
  await user.type(screen.getByRole('searchbox'), 'nobody')
  expect(screen.getByText('没有匹配的项目成员')).toBeInTheDocument()
  await user.clear(screen.getByRole('searchbox'))
  await user.selectOptions(screen.getByLabelText('筛选项目角色'), 'member')
  expect(screen.queryByText('Alice')).not.toBeInTheDocument()
})

