it('creates a plain account first and adds it only after a separate confirmation', async () => {
  let finishCreation!: (value: ManagedUser) => void
  const create = vi.spyOn(api, 'createUser').mockImplementation(() => new Promise(resolve => { finishCreation = resolve }))
  const add = vi.spyOn(api, 'addProjectMember').mockResolvedValue(createdMember)
  const user = userEvent.setup()
  render(<ProjectMembers {...props} canCreateAccounts />)
  await screen.findByText('Alice')
  await user.click(screen.getByRole('button', { name: '添加项目成员' }))
  expect(screen.getByLabelText('已有账号用户名')).toBeInTheDocument()
  await user.click(screen.getByRole('button', { name: '创建普通内置账号' }))
  await user.type(screen.getByLabelText('用户名'), 'carol')
  await user.type(screen.getByLabelText('显示名'), 'Carol')
  await user.type(screen.getByLabelText('初始密码'), 'Account-Start-2026!')
  await user.dblClick(screen.getByRole('button', { name: '确认创建账号' }))
  expect(create).toHaveBeenCalledOnce()
  expect(create).toHaveBeenCalledWith({ username: 'carol', display_name: 'Carol', password: 'Account-Start-2026!', platform_role: 'member' })
  expect(add).not.toHaveBeenCalled()
  await user.keyboard('{Escape}')
  expect(screen.getByRole('dialog')).toBeInTheDocument()
  await act(async () => finishCreation(createdAccount))
  expect(screen.getByRole('status')).toHaveTextContent('已创建，尚未加入项目')
  expect(screen.queryByLabelText('初始密码')).not.toBeInTheDocument()
  expect(within(screen.getByRole('dialog')).getByRole('combobox', { name: '项目角色' })).toHaveValue('member')
  expect(add).not.toHaveBeenCalled()
  await user.click(screen.getByRole('button', { name: '确认添加到项目' }))
  expect(add).toHaveBeenCalledWith('p1', { username: 'carol', role: 'member' })
  expect(await screen.findByText('Carol')).toBeInTheDocument()
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
})

