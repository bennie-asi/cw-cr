it.each(['success', 'failure'])('ignores late membership mutation %s after switching project', async result => {
  let resolve!: (value: ProjectMember) => void
  let reject!: (reason: Error) => void
  vi.spyOn(api, 'updateProjectMember').mockImplementation(() => new Promise((done, fail) => { resolve = done; reject = fail }))
  const refresh = vi.fn()
  const user = userEvent.setup()
  const view = render(<ProjectMembers {...props} currentUserId={8} onAccessChange={refresh} />)
  await screen.findByText('Alice')
  await openMemberAction(user, 'edit')
  await user.selectOptions(within(screen.getByRole('dialog')).getByLabelText('项目角色'), 'member')
  await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: '确认修改' }))
  vi.mocked(api.listProjectMembers).mockResolvedValue([])
  view.rerender(<ProjectMembers {...props} projectId="p2" currentUserId={8} onAccessChange={refresh} />)
  expect(await screen.findByText('尚未添加项目成员')).toBeInTheDocument()
  await act(async () => { if (result === 'success') resolve({ ...member, role: 'member' }); else reject(new Error('old project error')) })
  expect(refresh).not.toHaveBeenCalled()
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  expect(screen.queryByRole('alert')).not.toBeInTheDocument()
  expect(screen.queryByText('项目成员已更新')).not.toBeInTheDocument()
})

